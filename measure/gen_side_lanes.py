#!/usr/bin/env python3
"""Generate side_lanes.S: the lane-loop side-output kernel with blst's internal
AArch64 Montgomery routines inlined.

usage: python3 gen_side_lanes.py <blst checkout at f7a88067> > side_lanes.S

Copied from build/elf/mul_mont_384-armv8.S (Apache-2.0, Supranational):
  __mul_mont_384 (inlined twice), __sqr_384, __mul_by_1_mont_384 (once each).
v25 step 1 (NOT verbatim for sqr/BY1): the trailing `ret` of each body is
removed, and additionally:
  * __sqr_384: its 6 stores of the 12 square limbs to [x0] are dropped,
    because the square limbs stay in registers (x5, x19..x28, x16) and are
    fed straight into BY1 / parked by the driver in side_lanes.S.in;
  * __mul_by_1_mont_384: its 3 head loads of the low 6 limbs from [x1]
    are dropped, because the driver already placed those limbs in
    x11..x16 before BY1, and x1 now parks square limb L7 across BY1.
The driver (side_lanes.S.in) is new. The shipped side_lanes.S in this
folder was produced by applying exactly these edits to the v24 generated
file; re-running this generator (on an ARM host, see reproduce_lanes.sh)
must reproduce it byte for byte, or the measurement is invalid.
"""
import re, sys

src = open(sys.argv[1].rstrip("/") + "/build/elf/mul_mont_384-armv8.S").read()

def body(name):
    e = re.escape(name)
    m = re.search(r"^%s:\n(.*?)^\.size\t%s,\.-%s\n" % (e, e, e), src, re.S | re.M)
    if not m:
        raise SystemExit("routine %s not found" % name)
    b = m.group(1)
    assert not re.search(r"^\.L|^[A-Za-z_]\w*:", b, re.M), "unexpected label in " + name
    lines = b.rstrip("\n").split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    assert lines[-1].strip() == "ret", name
    assert "ret" not in "\n".join(l.split("//")[0] for l in lines[:-1]).split(), name
    assert not re.search(r"\b(x18|x30)\b", "\n".join(lines)), name
    body = lines[:-1]
    verb = "verbatim, ret dropped"
    if name == "__sqr_384":
        # v25 step 1: drop exactly the 6 stores of the square to [x0].
        dropped = [l for l in body if re.search(r"\bstp\b.*\[x0", l.split("//")[0])]
        assert len(dropped) == 6, dropped
        body = [l for l in body if not re.search(r"\bstp\b.*\[x0", l.split("//")[0])]
        verb = "edited (ret dropped, 6 square stores dropped: limbs stay in registers)"
    if name == "__mul_by_1_mont_384":
        # v25 step 1: drop exactly the 3 head loads of the low half from [x1].
        dropped = [l for l in body if re.search(r"\bldp\b.*\[x1", l.split("//")[0])]
        assert len(dropped) == 3, dropped
        body = [l for l in body if not re.search(r"\bldp\b.*\[x1", l.split("//")[0])]
        verb = "edited (ret dropped, 3 low-half loads dropped: inputs already in x11..x16)"
    return "\t// ---- inlined blst %s (%s)\n%s\n\t// ---- end %s\n" % (
        name, verb, "\n".join(body), name)

drv = open(sys.argv[0].replace("gen_side_lanes.py", "side_lanes.S.in")).read()
drv = drv.replace("@MUL@", body("__mul_mont_384")).replace("@SQR@", body("__sqr_384")) \
         .replace("@BY1@", body("__mul_by_1_mont_384"))
print("""// side_lanes.S -- generated by gen_side_lanes.py; do not edit by hand.
// Inlined bodies are blst's __mul_mont_384, __sqr_384, __mul_by_1_mont_384
// (commit f7a88067, build/elf/mul_mont_384-armv8.S). __mul_mont_384 is
// verbatim minus `ret`; __sqr_384 and __mul_by_1_mont_384 carry the v25
// step-1 edits documented in gen_side_lanes.py (square stores and low-half
// loads dropped; limbs pass in registers).
#ifndef __SIZEOF_POINTER__
#define __SIZEOF_POINTER__ 8
#endif
.text
""")
print(drv)
